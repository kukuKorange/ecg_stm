/**
  ******************************************************************************
  * @file    ecg_sim.h
  * @brief   ECG信号模拟器头文件
  *
  * @details 用软件生成标准PQRST心电波形，替代ADC硬件采样。
  *          可用于无传感器调试、波形显示演示和心率算法验证。
  *
  *          波形构成（单个心动周期比例）:
  *            0%- 8%  : 基线
  *            8%-20%  : P 波  (小正向圆波, +250)
  *           20%-24%  : PR段  (等电位基线)
  *           24%-27%  : Q 波  (小负向, -200)
  *           27%-31%  : R 上升 (线性, 0→+1500)
  *           31%-38%  : R 下降 (线性, +1500→-400)
  *           38%-46%  : S 恢复 (线性, -400→0)
  *           46%-51%  : ST段  (等电位基线)
  *           51%-81%  : T 波  (宽正向圆波, +500)
  *           81%-100% : TP段  (等电位基线)
  *
  *          使用方式: 在 kconfig.h 中启用 #define USE_ECG_SIM
  ******************************************************************************
  */

#ifndef __ECG_SIM_H
#define __ECG_SIM_H

#include <stdint.h>
#include "kconfig.h"

#ifdef USE_ECG_SIM

/*============================================================================*/
/*                              函数声明                                       */
/*============================================================================*/

/**
 * @brief  初始化ECG信号模拟器
 * @param  bpm: 模拟心率 (有效范围 30-200 bpm)
 * @note   在 main() 初始化阶段调用一次
 */
void ECG_Sim_Init(uint8_t bpm);

/**
 * @brief  获取下一个模拟ECG采样值
 * @retval ADC等效值 (0-4095), 基线约 2048
 * @note   每次调用推进一个采样点。
 *         应以与 ECG_SAMPLE_RATE (200Hz) 一致的速率调用，
 *         即在 ECG_SampleAndDraw() 中替代 AD_GetValue() 使用。
 */
uint16_t ECG_Sim_GetSample(void);

/**
 * @brief  设置模拟心率（运行时可调）
 * @param  bpm: 目标心率 (30-200 bpm)
 */
void ECG_Sim_SetBPM(uint8_t bpm);

/**
 * @brief  获取当前配置的模拟心率
 * @retval 模拟心率 (bpm)
 */
uint8_t ECG_Sim_GetBPM(void);

#endif /* USE_ECG_SIM */
#endif /* __ECG_SIM_H */
